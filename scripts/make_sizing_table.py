#!/usr/bin/env python3
"""Storage-sizing sensitivity: compare the reduced-storage plant (archived first study,
archive_reduced_storage/processed/eval_results.json, configs/reduced_storage.yaml) with the Tesla Model 3
plant (data/processed/eval_results.json, configs/nominal.yaml).
Writes paper/numbers_sizing.tex (macros \\G{<scale>:<item>:<key>}) and paper/tab_sizing.tex."""
import json, os
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = {"g": os.path.join(ROOT, "archive_reduced_storage", "processed", "eval_results.json"),
       "m": os.path.join(ROOT, "data", "processed", "eval_results.json")}
ITEMS = {"us06x1.0": "us06a", "us06x1.1": "us06b", "wltc_high_3bx1.0": "wh", "wltc_extrahigh_3x1.0": "wxa",
         "wltc_extrahigh_3x1.2": "wxb", "xtra:wmtc_allx1.0": "wmtc", "xtra:ftpmc1bx1.0": "ftp",
         "xtra:longHaulDriveCyclex1.0": "lh"}
V2 = ["A-DO-SMC + TD3 + filter v2 [s%d]" % s for s in (11, 22, 33)]
NOF = ["A-DO-SMC + TD3 no-filter [s%d]" % s for s in (11, 22, 33)]
FIX, MPCP, MPCV = "A-DO-SMC + fixed", "A-DO-SMC + MPC-EMS (persistence)", "A-DO-SMC + MPC-EMS (preview)"
L = [r"% AUTO-GENERATED by scripts/make_sizing_table.py",
     r"\makeatletter\newcommand{\G}[1]{\@ifundefined{g@#1}{\textcolor{red}{??#1}}{\@nameuse{g@#1}}}\makeatother"]
def kv(k, v): L.append(r"\expandafter\def\csname g@" + k + r"\endcsname{" + v + "}")
def mean(E, names, it, key, sc=1.0):
    return float(np.mean([np.mean([E[n][it][s][key] for s in E[n][it]]) for n in names])) * sc
for sk, path in SRC.items():
    E = json.load(open(path))["results"]
    for it, ik in ITEMS.items():
        if it not in E[FIX]:
            continue
        b = mean(E, [FIX], it, "ib_rms_A")
        v = mean(E, V2, it, "ib_rms_A")
        kv(f"{sk}:{ik}:dv2fix", f"{100 * (v - b) / b:+.1f}")
        kv(f"{sk}:{ik}:fixsat", f"{mean(E, [FIX], it, 'sat_frac', 100):.2f}")
        kv(f"{sk}:{ik}:v2sat", f"{mean(E, V2, it, 'sat_frac', 100):.2f}")
        kv(f"{sk}:{ik}:mpcpsat", f"{mean(E, [MPCP], it, 'sat_frac', 100):.2f}")
        m = mean(E, [MPCP], it, "ib_rms_A")
        kv(f"{sk}:{ik}:dv2mpcp", f"{100 * (v - m) / m:+.1f}")
        kv(f"{sk}:{ik}:v2dev", f"{mean(E, V2, it, 'max_dev_V'):.1f}")
        fails = sum(E[n][it][s]["status"] != "ok" for n in NOF if it in E[n] for s in E[n][it])
        runs = sum(len(E[n][it]) for n in NOF if it in E[n])
        kv(f"{sk}:{ik}:noffails", f"{fails}/{runs}" if runs else "--")
        kv(f"{sk}:{ik}:mpcvfails", str(sum(E[MPCV][it][s]["status"] != "ok" for s in E[MPCV][it])))
open(os.path.join(ROOT, "paper", "numbers_sizing.tex"), "w").write("\n".join(L) + "\n")
rows = [("us06x1.0", "US06"), ("us06x1.1", r"US06$\times1.1$"), ("wltc_high_3bx1.0", "WLTC high"),
        ("wltc_extrahigh_3x1.2", r"WLTC x-high$\times1.2$"), ("xtra:wmtc_allx1.0", "WMTC"),
        ("xtra:longHaulDriveCyclex1.0", "Long-haul")]
T = [r"\begin{table}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{2pt}",
     r"\caption{Storage-sizing sensitivity. R: reduced-storage plant (\SI{24}{kW} battery limit, \SI{60}{kW} rating, \SI{120}{F} SC); M3: Tesla Model 3 plant (\SI{57}{kW} battery limit, \SI{21}{F} SC). $\Delta i_b$: change of RMS battery current of TD3 + filter v2 relative to the fixed supervisor; Sat.: saturated time (\%); MPC: MPC-EMS with persistence forecast.}",
     r"\label{tab:sizing}", r"\begin{tabular}{@{}lrrrrrr@{}}", r"\toprule",
     r" & \multicolumn{2}{c}{$\Delta i_b$ (\%)} & \multicolumn{2}{c}{Sat.\ TD3 (\%)} & \multicolumn{2}{c}{Sat.\ MPC (\%)}\\",
     r"Cycle & R & M3 & R & M3 & R & M3\\", r"\midrule"]
for it, lab in rows:
    ik = ITEMS[it]
    T.append(f"{lab} & \\G{{g:{ik}:dv2fix}} & \\G{{m:{ik}:dv2fix}} & \\G{{g:{ik}:v2sat}} & \\G{{m:{ik}:v2sat}} & \\G{{g:{ik}:mpcpsat}} & \\G{{m:{ik}:mpcpsat}}\\\\")
T += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
open(os.path.join(ROOT, "paper", "tab_sizing.tex"), "w").write("\n".join(T) + "\n")
print("numbers_sizing.tex / tab_sizing.tex written")

# filter bounds of the reduced-storage plant (for the design-history text)
import sys, yaml  # noqa: E402
sys.path.insert(0, os.path.join(ROOT, "src"))
from hess.supervisors import SafetyFilter  # noqa: E402
cg = yaml.safe_load(open(os.path.join(ROOT, "configs", "reduced_storage.yaml")))
cm = yaml.safe_load(open(os.path.join(ROOT, "configs", "nominal.yaml")))
with open(os.path.join(ROOT, "paper", "numbers_sizing.tex"), "a") as fh:
    for tag, c in (("G", cg), ("M", cm)):
        for v in (1, 2):
            f = SafetyFilter(c, True, v)
            f(np.array([0.2, c["supervision"]["vsc_ref"]["value"], 250.0]), np.zeros(3), c["plant"]["ocv_nom"]["value"])
            fh.write("\\newcommand{\\%sVloV%s}{%.0f}\n" % (tag, "one" if v == 1 else "two", f.v_lo_last))
        vpow = (c["vehicle"]["P_trac_max"]["value"] - c["plant"]["ocv_nom"]["value"] * c["limits"]["Ibmax"]["value"]) / c["limits"]["Iscmax"]["value"]
        fh.write("\\newcommand{\\%sVpow}{%.0f}\n\\newcommand{\\%sEresKJ}{%.0f}\n" % (tag, vpow, tag, c["agent"]["reserve_energy_J"] / 1e3))
        fh.write("\\newcommand{\\%sBoxLo}{%.0f}\n" % (tag, c["agent"]["vsc_range"][0]))
print("filter-bound macros appended")

# Model 3 mechanism: share of US06 samples with v_sc,ref at the filter lower bound (v2 agents, seed 101 logs)
import glob  # noqa: E402
fr = []
for fpath in sorted(glob.glob(os.path.join(ROOT, "data", "raw", "eval", "us06_x1.0_A-DO-SMC__TD3__filter_v2_s*.npz"))):
    fr.append(float(np.mean(np.load(fpath)["vsc_ref"] <= cm["agent"]["vsc_range"][0] + 15.0)))
CACHE = os.path.join(ROOT, "data", "processed", "vscref_at_bound.json")   # cached so the paper builds without raw logs
if fr:
    json.dump(fr, open(CACHE, "w"))
else:
    fr = json.load(open(CACHE))
M = json.load(open(os.path.join(ROOT, "data", "processed", "mechanism_diagnostics.json")))
v2m = [M[k]["vsc_ref_mean"] for k in M if "filter_v2" in k and "x1.2" not in k and not k.startswith("paper")]
with open(os.path.join(ROOT, "paper", "numbers_sizing.tex"), "a") as fh:
    fh.write("\\newcommand{\\MAtBoundMin}{%.0f}\n\\newcommand{\\MAtBoundMax}{%.0f}\n" % (100 * min(fr), 100 * max(fr)))
    fh.write("\\newcommand{\\MVrefMeanVtwoMin}{%.0f}\n\\newcommand{\\MVrefMeanVtwoMax}{%.0f}\n" % (min(v2m), max(v2m)))
print("mechanism macros appended", fr)
