#!/usr/bin/env python3
"""Additional checks requested in the self-review (paper/numbers_checks.tex, paper/tab_loss.tex):
 (1) resistive losses (battery R0 + r_b, SC ESR + r_sc) from the seed-101 logs of the main evaluation;
 (2) the estimator condition k_s >= |D_tilde| on Model 3 test logs (A-DO-SMC + fixed, measurement noise on,
     10 ms logging resolution, t > 0.2 s);
 (3) the SC-mass sensitivity (data/processed/mass_sensitivity.json)."""
import json, os
import numpy as np, yaml
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "raw", "eval")
cfg = yaml.safe_load(open(os.path.join(ROOT, "configs", "nominal.yaml"))); P = cfg["plant"]
E = json.load(open(os.path.join(ROOT, "data", "processed", "eval_results.json")))["results"]
L = [r"% AUTO-GENERATED by scripts/make_extra_checks.py"]
def nc(k, v): L.append("\\newcommand{\\%s}{%s}" % (k, v))
def log(name, item):
    d = E[name][item]; return np.load(os.path.join(RAW, d[sorted(d)[0]]["raw"] + ".npz"))
def loss_wh(d):
    t = d["t"]; dt = np.gradient(t)
    pb = (P["R0b"]["value"] + P["rb"]["value"]) * d["iLb"] ** 2
    ps = (P["Resr"]["value"] + P["rsc"]["value"]) * d["iLsc"] ** 2
    return float((pb * dt).sum()) / 3.6e3, float((ps * dt).sum()) / 3.6e3
ITEMS = [("us06x1.0", "US06"), ("wltc_high_3bx1.0", "WLTC high"), ("wltc_extrahigh_3x1.0", "WLTC x-high"),
         ("xtra:wmtc_allx1.0", "WMTC"), ("xtra:ftpmc1bx1.0", "FTP-MC1b")]
CF = [("A-DO-SMC + fixed", "Fixed"), ("A-DO-SMC + rule", "Rule"), ("A-DO-SMC + MPC-EMS (persistence)", "MPC-EMS")]
V2 = ["A-DO-SMC + TD3 + filter v2 [s%d]" % s for s in (11, 22, 33)]
rows = []; rel = {}
for it, lab in ITEMS:
    tot = {}
    cells = []
    for n, nl in CF:
        b, s = loss_wh(log(n, it)); tot[nl] = b + s; cells.append(f"{b:.1f} / {s:.1f}")
    v = [sum(loss_wh(log(n, it))) for n in V2]
    vb = [loss_wh(log(n, it)) for n in V2]
    cells.append(f"{np.mean([x[0] for x in vb]):.1f} / {np.mean([x[1] for x in vb]):.1f}")
    tot["TD3"] = float(np.mean(v))
    r = {k: 100 * (tot[k] - tot["Fixed"]) / tot["Fixed"] for k in tot}
    rel[lab] = (r, [100 * (x - tot["Fixed"]) / tot["Fixed"] for x in v])
    rows.append(f"{lab} & " + " & ".join(cells) + f" & {r['Rule']:+.1f} & {r['MPC-EMS']:+.1f} & {r['TD3']:+.1f}\\\\")
T = [r"\begin{table*}[t]", r"\centering\footnotesize",
     r"\caption{Resistive losses on the Tesla Model 3 plant (noise seed 101; battery $R_0+r_b$ / SC $R_{esr}+r_{sc}$, in Wh; TD3: mean of the three filter-v2 agents) and change of the total relative to the fixed supervisor. Switching, core and drive-unit losses are not modelled.}",
     r"\label{tab:loss}", r"\begin{tabular}{@{}lccccrrr@{}}", r"\toprule",
     r" & \multicolumn{4}{c}{Battery / SC loss (Wh)} & \multicolumn{3}{c}{$\Delta$ total vs fixed (\%)}\\",
     r"Cycle & Fixed & Rule & MPC-EMS & TD3 & Rule & MPC-EMS & TD3\\", r"\midrule"] + rows + \
    [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
open(os.path.join(ROOT, "paper", "tab_loss.tex"), "w").write("\n".join(T) + "\n")
td3 = [rel[l][0]["TD3"] for _, l in ITEMS]; seeds = [x for _, l in ITEMS for x in rel[l][1]]
mp = [rel[l][0]["MPC-EMS"] for _, l in ITEMS]
assert max(td3) < 0 and max(mp) < 0, "text assumes reductions"
nc("LossTDMin", f"{-max(td3):.1f}"); nc("LossTDMax", f"{-min(td3):.1f}")
nc("LossTDSeedMax", f"{max(seeds):+.1f}"); nc("LossMPCMin", f"{-max(mp):.1f}"); nc("LossMPCMax", f"{-min(mp):.1f}")
nc("LossTDUSSeedMax", f"{max(rel['US06'][1]):.1f}")
# (2) estimator condition
fr, mr = [], []
for it in ("us06x1.0", "us06x1.1", "wltc_high_3bx1.0", "wltc_extrahigh_3x1.0", "wltc_extrahigh_3x1.2"):
    d = log("A-DO-SMC + fixed", it); m = d["t"] > 0.2
    r = d["ks"][m] / np.maximum(np.abs(d["Dtrue"] - d["Dhat"])[m], 1e-9)
    fr.append(np.mean(r >= 1.0)); mr.append(r.min())
nc("AsmMThreeFrac", f"{100 * min(fr):.0f}"); nc("AsmMThreeMinRatio", f"{min(mr):.2f}")
# (3) mass
M = json.load(open(os.path.join(ROOT, "data", "processed", "mass_sensitivity.json")))
nc("MassAddKg", f"{M['added_mass_kg']:.0f}")
inc = [100 * (v["ib_rms_A"] - v["ref"]["ib_rms_A"]) / v["ref"]["ib_rms_A"] for v in M["runs"].values()]
nc("MassIbIncMin", f"{min(inc):.1f}"); nc("MassIbIncMax", f"{max(inc):.1f}")
nc("MassSatMax", f"{100 * max(v['sat_frac'] for v in M['runs'].values()):.2f}")
def mean_ib(prefix, item, ref=False):
    vals = [(v["ref"] if ref else v)["ib_rms_A"] for k, v in M["runs"].items() if k.startswith(prefix) and k.endswith("|" + item)]
    return float(np.mean(vals))
for item, tag in (("us06", "US"), ("wltc_high_3b", "WH")):
    f, t = mean_ib("A-DO-SMC + fixed", item), mean_ib("A-DO-SMC + TD3 + filter v2", item)
    nc(f"MassDvtwoFix{tag}", f"{100 * (t - f) / f:+.1f}")
    fr_, tr_ = mean_ib("A-DO-SMC + fixed", item, True), mean_ib("A-DO-SMC + TD3 + filter v2", item, True)
    nc(f"MassDvtwoFixRef{tag}", f"{100 * (tr_ - fr_) / fr_:+.1f}")
open(os.path.join(ROOT, "paper", "numbers_checks.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(L)); print("\n".join(rows))
