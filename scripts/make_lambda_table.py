#!/usr/bin/env python3
"""paper/tab_lambda.tex and paper/numbers_lambda.tex from data/processed/lambda_robustness.json."""
import json, os
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = json.load(open(os.path.join(ROOT, "data", "processed", "lambda_robustness.json")))
R = D["results"]
L = ["% AUTO-GENERATED by scripts/make_lambda_table.py"]
def nc(k, v): L.append("\\newcommand{\\%s}{%s}" % (k, v))
def mx(c, t, it): return float(np.mean([v["max_dev_V"] for v in R[c][t][it].values()]))
def rr(c, t, it): return R[c][t][it]["101"]["cond_minratio"]
def sat(c, t, it): return float(np.mean([v["sat_frac"] for v in R[c][t][it].values()]))
CASES = [("lam100", r"constant, $\lambda=\lambda_{\min}$"), ("lam250", r"constant, nominal"), ("lam800", r"constant, $\lambda=\lambda_{\max}$"),
         ("agent11", "TD3 agent, seed 11"), ("agent22", "TD3 agent, seed 22"), ("agent33", "TD3 agent, seed 33")]
IT = ["us06x1.0", "us06x1.1"]
T = [r"\begin{table*}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{4pt}",
     r"\caption{Robustness of tier 1 to the observer gain on US06 (Tesla Model 3 plant). Hi: fixed high-gain DO-SMC ($k_s=\KsHi$\,V/s, sized at the nominal $\lambda=\SI{250}{s^{-1}}$); A: A-DO-SMC. Agent rows replay open-loop the schedule $(\tau_b,v_{sc,ref},\lambda)(t)$ chosen by each filter-v2 agent in its evaluation run, so both controllers see the same $\lambda(t)$. max$|e|$: mean over noise seeds 101--103; $r_{\min}=\min_t k_s/|\Dt|$ ($t>0.2$\,s, seed 101, \SI{1}{ms} logging). $^\ddagger$Power deficit (input saturated \LamSatPct\,\% of the time, capability condition (H3) violated).}",
     r"\label{tab:lambda}", r"\begin{tabular}{@{}llcccccccc@{}}", r"\toprule",
     r" & & \multicolumn{4}{c}{US06} & \multicolumn{4}{c}{US06$\times1.1$}\\\cmidrule(lr){3-6}\cmidrule(lr){7-10}",
     r"$\lambda$ schedule & $\lambda$ range (s$^{-1}$) & \multicolumn{2}{c}{max$|e|$ (V)} & \multicolumn{2}{c}{$r_{\min}$} & \multicolumn{2}{c}{max$|e|$ (V)} & \multicolumn{2}{c}{$r_{\min}$}\\",
     r" & & Hi & A & Hi & A & Hi & A & Hi & A\\", r"\midrule"]
for c, lab in CASES:
    s = R[c]["a"]["us06x1.0"]["101"]; s2 = R[c]["a"]["us06x1.1"]["101"]
    lo = min(s["lam_min"], s2["lam_min"]); hi = max(s["lam_max"], s2["lam_max"])
    rng = f"{lo:.0f}" if abs(hi - lo) < 1 else f"{lo:.0f}--{hi:.0f}"
    cells = []
    for it in IT:
        dag = r"$^\ddagger$" if sat(c, "a", it) > 0 else ""
        cells += [f"{mx(c, 'hi', it):.2f}{dag}", f"{mx(c, 'a', it):.2f}{dag}", f"{rr(c, 'hi', it):.3f}", f"{rr(c, 'a', it):.3f}"]
    T.append(f"{lab} & {rng} & " + " & ".join(cells) + r"\\")
    if c == "lam800":
        T.append(r"\midrule")
T += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
open(os.path.join(ROOT, "paper", "tab_lambda.tex"), "w").write("\n".join(T) + "\n")

nc("LamHiUSMax", f"{mx('lam100', 'hi', 'us06x1.0'):.1f}"); nc("LamAUSMax", f"{mx('lam100', 'a', 'us06x1.0'):.2f}")
nc("LamHiUSbMax", f"{mx('lam100', 'hi', 'us06x1.1'):.1f}"); nc("LamAUSbMax", f"{mx('lam100', 'a', 'us06x1.1'):.2f}")
nc("LamHiUSRatio", f"{rr('lam100', 'hi', 'us06x1.0'):.2f}"); nc("LamAUSRatio", f"{rr('lam100', 'a', 'us06x1.0'):.2f}")
nc("LamHiUSFail", f"{100 - 100 * R['lam100']['hi']['us06x1.0']['101']['cond_frac']:.2f}")
nc("LamHiUSFrac", f"{100 * R['lam100']['hi']['us06x1.0']['101']['cond_frac']:.2f}")
nc("LamNomUSMax", f"{mx('lam250', 'a', 'us06x1.0'):.2f}"); nc("LamMaxUSMax", f"{mx('lam800', 'a', 'us06x1.0'):.2f}")
nc("LamFactorHi", f"{mx('lam100', 'hi', 'us06x1.0') / mx('lam100', 'a', 'us06x1.0'):.1f}")
ag = [c for c, _ in CASES if c.startswith("agent")]
amin = min(min(R[c]["a"][it]["101"]["lam_min"] for it in IT) for c in ag)
amean_lo = min(min(R[c]["a"][it]["101"]["lam_mean"] for it in IT) for c in ag)
amean_hi = max(max(R[c]["a"][it]["101"]["lam_mean"] for it in IT) for c in ag)
nc("LamAgentMin", f"{amin:.0f}"); nc("LamAgentMeanLo", f"{amean_lo:.0f}"); nc("LamAgentMeanHi", f"{amean_hi:.0f}")
okr = [rr(c, "a", it) for c, _ in CASES for it in IT if sat(c, "a", it) == 0]
nc("LamARatioMin", f"{min(okr):.3f}")
okh = [rr(c, "hi", it) for c in ag for it in IT if sat(c, "hi", it) == 0]
nc("LamHiAgentRatioMin", f"{min(okh):.3f}")
nc("LamSatPct", f"{100 * max(sat(c, 'a', it) for c in ag for it in IT):.2f}")
diff = max(abs(mx(c, "hi", it) - mx(c, "a", it)) for c in ag for it in IT if sat(c, "a", it) == 0)
nc("LamAgentMaxDiff", f"{diff:.3f}")
open(os.path.join(ROOT, "paper", "numbers_lambda.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(T)); print("\n".join(L))
