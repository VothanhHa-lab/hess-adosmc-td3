#!/usr/bin/env python3
"""Supplementary table: observer-gain robustness and DO-ASMC comparison on WLTC extra-high (x1.0, x1.2),
from data/processed/lambda_robustness.json and data/processed/asmc_compare.json.
Output: paper/tab_wltc.tex, paper/numbers_wltc.tex"""
import json, os
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LR = json.load(open(os.path.join(ROOT, "data", "processed", "lambda_robustness.json")))["results"]
AC = json.load(open(os.path.join(ROOT, "data", "processed", "asmc_compare.json")))["results"]
IT = ["wltc_extrahigh_3x1.0", "wltc_extrahigh_3x1.2"]
def mean(R, c, t, it, k="max_dev_V"): return float(np.mean([v[k] for v in R[c][t][it].values()]))
CASES = [("lam100", r"$\lambda=100$"), ("lam250", r"$\lambda=250$"), ("lam800", r"$\lambda=800$"),
         ("agent11", "agent 11"), ("agent22", "agent 22"), ("agent33", "agent 33")]
COLS = [("hi", LR), ("a", AC), ("afix", AC), ("asmc", AC), ("asmck", AC)]
T = [r"\begin{table*}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{3.5pt}",
     r"\caption{Observer-gain robustness and DO-ASMC comparison on WLTC extra-high (held-out, Tesla Model 3 plant), same variants and protocol as Tables~\ref{tab:asmc} and~\ref{tab:lambda}. Hi: fixed high-gain DO-SMC; A: A-DO-SMC; A$\phi_0$: A-DO-SMC with fixed layer; As: DO-ASMC, tuned; Ak: DO-ASMC, bounded. max$|e|$ and RMS $\Delta u$: mean over noise seeds 101--103; $r_{\min}$: seed 101. No variant saturated the input.}",
     r"\label{tab:wltc}", r"\begin{tabular}{@{}l" + "c" * 14 + r"@{}}", r"\toprule",
     r" & \multicolumn{7}{c}{WLTC extra-high} & \multicolumn{7}{c}{WLTC extra-high$\times1.2$}\\\cmidrule(lr){2-8}\cmidrule(lr){9-15}",
     r" & \multicolumn{5}{c}{max$|e|$ (V)} & \multicolumn{2}{c}{$r_{\min}$} & \multicolumn{5}{c}{max$|e|$ (V)} & \multicolumn{2}{c}{$r_{\min}$}\\",
     r"$\lambda$ schedule & Hi & A & A$\phi_0$ & As & Ak & Hi & A & Hi & A & A$\phi_0$ & As & Ak & Hi & A\\", r"\midrule"]
sat = 0.0; rA = []; dmax = 0.0
for c, lab in CASES:
    cells = []
    for it in IT:
        cells += [f"{mean(R, c, t, it):.2f}" for t, R in COLS]
        cells += [f"{LR[c][t][it]['101']['cond_minratio']:.2f}" for t in ("hi", "a")]
        sat = max(sat, max(mean(R, c, t, it, "sat_frac") for t, R in COLS))
        rA.append(LR[c]["a"][it]["101"]["cond_minratio"])
        v = [mean(R, c, t, it) for t, R in COLS if t != "afix"]; dmax = max(dmax, max(v) - min(v))
    T.append(lab + " & " + " & ".join(cells) + r"\\")
    if c == "lam800": T.append(r"\midrule")
T += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
open(os.path.join(ROOT, "paper", "tab_wltc.tex"), "w").write("\n".join(T) + "\n")
allmax = [mean(R, c, t, it) for c, _ in CASES for t, R in COLS for it in IT]
rhi = [LR[c]["hi"][it]["101"]["cond_minratio"] for c, _ in CASES for it in IT]
L = ["% AUTO-GENERATED by scripts/make_wltc_table.py",
     r"\newcommand{\WlMaxLo}{%.2f}" % min(allmax), r"\newcommand{\WlMaxHi}{%.2f}" % max(allmax),
     r"\newcommand{\WlSpread}{%.2f}" % dmax, r"\newcommand{\WlSatMax}{%.2f}" % (100 * sat),
     r"\newcommand{\WlHiRatioMin}{%.2f}" % min(rhi), r"\newcommand{\WlARatioMin}{%.2f}" % min(rA)]
open(os.path.join(ROOT, "paper", "numbers_wltc.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(T)); print("\n".join(L))
