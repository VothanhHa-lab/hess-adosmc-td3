#!/usr/bin/env python3
"""Tier-1 results on the Tesla Model 3 plant: paper/tab_tier1.tex, paper/numbers_tier1.tex and
results/figures/F2_tier1_m3_us06.{pdf,png}. Inputs: data/processed/eval_results.json (PI, low-gain DO-SMC,
robust MPC, A-DO-SMC; noise seeds 101-103) and data/processed/tier1_m3.json (high-gain DO-SMC, 1 ms logs)."""
import json, os, sys
import numpy as np, yaml
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from hess import plots  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402

cfg = yaml.safe_load(open(os.path.join(ROOT, "configs", "nominal.yaml")))
E = json.load(open(os.path.join(ROOT, "data", "processed", "eval_results.json")))["results"]
T = json.load(open(os.path.join(ROOT, "data", "processed", "tier1_m3.json")))
RAW = os.path.join(ROOT, "data", "raw", "tier1_m3")
VREF = cfg["control"]["vref"]["value"]
L = ["% AUTO-GENERATED by scripts/make_tier1_m3.py"]
def nc(k, v): L.append("\\newcommand{\\%s}{%s}" % (k, v))

def mean_eval(name, item, key):
    return float(np.mean([v[key] for v in E[name][item].values()]))
def mean_hi(item, key):
    return float(np.mean([v[key] for v in T["results"]["dosmc_hi"][item].values()]))

ITEMS = [("us06x1.0", r"US06"), ("us06x1.1", r"US06$\times1.1$"), ("wltc_extrahigh_3x1.2", r"WLTC x-high$\times1.2$")]
ROWS = [("PI + fixed", r"PI (same small-signal poles)", r"\TimePI"),
        ("DO-SMC (paper) + fixed", r"DO-SMC, low gain ($k_s=120$\,V/s)", r"\TimeDOSMC"),
        ("HI", r"DO-SMC, high gain ($k_s=\KsHi$\,V/s)", r"\TimeDOSMC"),
        ("Robust MPC + fixed", r"Robust MPC (offset-free, $N=20$)", r"\TimeMPC"),
        ("A-DO-SMC + fixed", r"A-DO-SMC (proposed tier 1)", r"\TimeADOSMC")]
tab = [r"\begin{table*}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{5pt}",
       r"\caption{Tier-1 comparison on held-out drive cycles of the Tesla Model 3 plant (fixed supervisor, mean over noise seeds 101--103). The last column is the median time of one controller update on the simulation host.}",
       r"\label{tab:tier1}", r"\begin{tabular}{@{}l" + "cc" * len(ITEMS) + "c@{}}", r"\toprule",
       " & " + " & ".join(r"\multicolumn{2}{c}{%s}" % lab for _, lab in ITEMS) + r" & Update\\",
       r"Outer loop" + r" & max$|e|$ (V) & RMS $e$ (V)" * len(ITEMS) + r" & (\si{\micro s})\\", r"\midrule"]
val = {}
for name, lab, tm in ROWS:
    cells = []
    for it, _ in ITEMS:
        mx = mean_hi(it, "max_dev_V") if name == "HI" else mean_eval(name, it, "max_dev_V")
        rm = mean_hi(it, "rms_e_V") if name == "HI" else mean_eval(name, it, "rms_e_V")
        val[(name, it)] = (mx, rm)
        cells += [f"{mx:.2f}", f"{rm:.3f}"]
    tab.append(lab + " & " + " & ".join(cells) + f" & {tm}" + r"\\")
tab += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
open(os.path.join(ROOT, "paper", "tab_tier1.tex"), "w").write("\n".join(tab) + "\n")

tags = {"PI + fixed": "PI", "DO-SMC (paper) + fixed": "Lo", "HI": "Hi", "Robust MPC + fixed": "MPC", "A-DO-SMC + fixed": "A"}
cyc = {"us06x1.0": "US", "us06x1.1": "USb", "wltc_extrahigh_3x1.2": "WX"}
for (name, it), (mx, rm) in val.items():
    nc(f"TOne{tags[name]}{cyc[it]}Max", f"{mx:.2f}"); nc(f"TOne{tags[name]}{cyc[it]}Rms", f"{rm:.3f}")
# high gain on the two remaining test items (text)
for it, tg in (("wltc_high_3bx1.0", "WH"), ("wltc_extrahigh_3x1.0", "WXa")):
    nc(f"TOneHi{tg}Max", f"{mean_hi(it, 'max_dev_V'):.2f}"); nc(f"TOneA{tg}Max", f"{mean_eval('A-DO-SMC + fixed', it, 'max_dev_V'):.2f}")

kp = T["kprime"]
nc("KsHi", f"{T['ks_hi']:.0f}"); nc("PhiHi", f"{T['phi_hi']:.0f}")
nc("TrainDtMax", f"{max(T['train_Dtilde_max'].values()):.0f}")
R = T["results"]
def one(tag):
    return R[tag]["us06x1.0"]["101"]
lo, lonn, hi, a, ann = one("dosmc"), one("dosmc_nonoise"), one("dosmc_hi_log"), one("adosmc"), one("adosmc_nonoise")
nc("DtLoUS", f"{lo['Dtilde_max']:.0f}"); nc("DtLoUSnn", f"{lonn['Dtilde_max']:.0f}")
nc("DtLoRatio", f"{lonn['Dtilde_max'] / 120.0:.1f}")
nc("CondLoFrac", f"{100 * lonn['cond_frac']:.0f}")
nc("CondHiFrac", f"{100 * hi['cond_frac']:.1f}"); nc("CondHiMin", f"{hi['cond_minratio']:.2f}")
nc("DtHiUS", f"{hi['Dtilde_max']:.0f}")
nc("AssumptionHoldPct", f"{100 * ann['cond_frac']:.1f}\\,\\%"); nc("MinKsRatio", f"{ann['cond_minratio']:.2f}")
d = np.load(os.path.join(RAW, "adosmc_nonoise_us06_x1.0_s101.npz")); m = d["t"] > 0.2
DtA = float(np.abs(d["Dtrue"] - d["Dhat"])[m].max()); KsA = float(d["ks"][m].max())
nc("DtildeMaxAdapt", f"{DtA:.0f}"); nc("KsMaxAdapt", f"{KsA:.0f}")
nc("AsmNoisyFrac", f"{100 * a['cond_frac']:.1f}"); nc("AsmNoisyMinRatio", f"{a['cond_minratio']:.2f}")
# appendix illustration: W = sup|Dt| + sup ks, capability at nominal operating point
Cdc = cfg["plant"]["Cdc"]["value"]; W = DtA + KsA
vb = cfg["plant"]["ocv_nom"]["value"]; vsc = cfg["supervision"]["vsc_ref"]["value"] if "vsc_ref" in cfg["supervision"] else 312.5
cap = (vb * cfg["limits"]["Ibmax"]["value"] + vsc * cfg["limits"]["Iscmax"]["value"]) / VREF
nc("AppW", f"{W / 1e3:.1f}"); nc("AppTwoW", f"{2 * W / 1e3:.1f}"); nc("AppTwoWA", f"{2 * W * Cdc:.0f}")
nc("AppCap", f"{cap:.0f}"); nc("AppVb", f"{vb:.0f}"); nc("AppVsc", f"{vsc:.1f}"); nc("AppVdc", f"{VREF:.0f}")
nc("AppDelta", f"{120.0 / ann['cond_minratio']:.0f}")
open(os.path.join(ROOT, "paper", "numbers_tier1.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(L))

# ---------------- figure
plots.style()
S = {"dosmc": ("DO-SMC, low gain", "#D55E00", "-"), "adosmc": ("A-DO-SMC (proposed)", "#0072B2", "-"),
     "dosmc_hi_log": ("DO-SMC, high gain", "#CC79A7", (0, (4, 2))), "mpc": ("Robust MPC", "#009E73", (0, (1, 1.5)))}
D = {k: np.load(os.path.join(RAW, f"{k}_us06_x1.0_s101.npz")) for k in S}
da = D["adosmc"]
# zoom window around the largest A-DO-SMC/low-gain deviation
dl = D["dosmc"]; ml = dl["t"] > 0.5
tpk = float(dl["t"][ml][np.argmax(np.abs(dl["vdc"][ml] - VREF))])
w0, w1 = tpk - 1.5, tpk + 2.5
fig, axs = plt.subplots(2, 2, figsize=(plots.W2, 3.6), gridspec_kw={"width_ratios": [2, 1]})
for k, (lab, col, ls) in S.items():
    d = D[k]
    axs[0, 0].plot(d["t"], d["vdc"] - VREF, linestyle=ls, color=col, label=lab, lw=1.2)
    mm = (d["t"] >= w0) & (d["t"] <= w1)
    axs[0, 1].plot(d["t"][mm], d["vdc"][mm] - VREF, linestyle=ls, color=col, lw=1.2)
BB = dict(boxstyle="round,pad=0.15", fc="white", ec="none", alpha=0.85)
for k, off in (("dosmc", (40, -1.5)), ("adosmc", (60, 2.5))):
    d = D[k]; mk = d["t"] > 0.5
    j = np.argmax(np.abs(d["vdc"][mk] - VREF)); tk, ek = d["t"][mk][j], d["vdc"][mk][j] - VREF
    axs[0, 0].annotate(f"max $|e|$ = {abs(ek):.2f} V", xy=(tk, ek), xytext=(tk + off[0], ek + off[1]), fontsize=6.5,
                       color=S[k][1], bbox=BB, arrowprops=dict(arrowstyle="->", color=S[k][1], lw=0.8))
da = np.load(os.path.join(RAW, "adosmc_nonoise_us06_x1.0_s101.npz"))
mm = (da["t"] >= w0) & (da["t"] <= w1)
axs[1, 0].semilogy(da["t"][mm], da["ks"][mm], color="#0072B2", label=r"$k_s(t)$, A-DO-SMC")
axs[1, 0].semilogy(da["t"][mm], np.abs(da["Dtrue"] - da["Dhat"])[mm] + 1, color="0.5", label=r"$|\tilde D(t)|$, A-DO-SMC")
axs[1, 0].axhline(120, color="#D55E00", lw=1.0, ls=":", label=r"$k_s$ low gain")
axs[1, 0].axhline(T["ks_hi"], color="#CC79A7", lw=1.0, ls=":", label=r"$k_s$ high gain")
axs[1, 1].plot(da["t"][mm], da["phi"][mm], color="#0072B2", label="A-DO-SMC")
axs[1, 1].axhline(T["phi_hi"], color="#CC79A7", lw=1.0, ls=":", label="high gain")
axs[1, 1].axhline(0.5, color="#D55E00", lw=1.0, ls=":", label="low gain")
axs[1, 0].text(0.02, 0.04, r"noise-free run: $k_s\geq|\tilde D|$ in %.1f %% of" "\n" r"samples, min. ratio %.2f"
               % (100 * ann["cond_frac"], ann["cond_minratio"]), transform=axs[1, 0].transAxes, fontsize=6, color="#0072B2", bbox=BB)
axs[0, 1].text(0.97, 0.05, "zoom: largest transient", transform=axs[0, 1].transAxes, fontsize=6.5, ha="right", bbox=BB)
axs[0, 0].set_ylabel(r"$e=v_{dc}-v^*_{dc}$ (V)"); axs[0, 0].set_xlabel("Time (s)")
axs[0, 0].legend(loc="lower center", bbox_to_anchor=(0.75, 1.02), ncol=4, frameon=False)
axs[1, 0].set_ylabel("V/s"); axs[1, 0].set_ylim(1, 1e5); axs[1, 0].legend(loc="upper left", ncol=2, fontsize=6, frameon=False)
axs[1, 1].set_ylabel(r"$\phi_s(t)$ (V)"); axs[1, 1].set_ylim(0, 11); axs[1, 1].legend(loc="upper left", ncol=2, fontsize=5.5, frameon=False, handlelength=1.2, columnspacing=0.6)
for ax in (axs[0, 1], axs[1, 0], axs[1, 1]):
    ax.set_xlabel("Time (s)")
# ---- in-figure notes
for ax, lab in zip((axs[0, 0], axs[0, 1], axs[1, 0], axs[1, 1]), ("(a)", "(b)", "(c)", "(d)")):
    plots.panel_label(ax, lab)
axs[0, 0].set_ylim(-7.5, 10.5)
axs[0, 0].text(0.06, 0.965, "high gain and robust MPC overlap A-DO-SMC (max $|e|$ about 1.5 V)",
               transform=axs[0, 0].transAxes, fontsize=6, ha="left", va="top", bbox=plots.BOX)
mz = (dl["t"] >= w0) & (dl["t"] <= w1); jz = np.argmax(np.abs(dl["vdc"][mz] - VREF))
tz, ez = dl["t"][mz][jz], dl["vdc"][mz][jz] - VREF
plots.note(axs[0, 1], "low gain: $k_s<|\\tilde D|$,\nerror leaves the layer", (tz, ez), (tz + 1.15, 0.75 * ez), color="#D55E00")
axs[0, 1].text(0.58, 0.22, "A-DO-SMC, high gain\nand MPC stay near 0", transform=axs[0, 1].transAxes, fontsize=6,
               color="#0072B2", bbox=plots.BOX)
Dt = np.abs(da["Dtrue"] - da["Dhat"]); jd = np.argmax(Dt[mm]); td, vd = da["t"][mm][jd], Dt[mm][jd]
jk = np.argmax(da["ks"][mm]); tk2, vk = da["t"][mm][jk], da["ks"][mm][jk]
plots.note(axs[1, 0], "$k_s$ follows $|\\tilde D|$ from above:\nreaching condition holds", (tk2, vk), (300.95, 1.5e5), color="#0072B2")
plots.note(axs[1, 0], "$|\\tilde D|$ peak %.0f V/s, %.0f times\nthe low gain of 120 V/s" % (vd, vd / 120.0), (td, vd + 1),
           (300.95, 9.0), color="0.3")
axs[1, 0].text(0.99, 0.42, "steady state:\n$k_s\\to k_{\\min}$", transform=axs[1, 0].transAxes, fontsize=6, ha="right",
               color="#0072B2", bbox=plots.BOX)
jp = np.argmax(da["phi"][mm]); tp, vp = da["t"][mm][jp], da["phi"][mm][jp]
plots.note(axs[1, 1], "$\\phi_s=k_s/k'$ widens with\nthe gain: poles stay fixed", (tp, vp), (299.0, 9.0), color="#0072B2")
axs[1, 0].set_ylim(1, 1e6)
axs[1, 0].legend(loc="upper left", ncol=1, fontsize=6, frameon=False, bbox_to_anchor=(0.06, 1.0), labelspacing=0.25)
axs[1, 1].legend(loc="center right", ncol=1, fontsize=5.5, frameon=False, handlelength=1.2, bbox_to_anchor=(1.0, 0.55))
plots.save(fig, os.path.join(ROOT, "results", "figures", "F2_tier1_m3_us06"))
nc_txt = f"zoom window {w0:.1f}-{w1:.1f} s"
open(os.path.join(ROOT, "paper", "numbers_tier1.tex"), "a").write("\\newcommand{\\ZoomA}{%.1f}\n\\newcommand{\\ZoomB}{%.1f}\n" % (w0, w1))
print(nc_txt)
