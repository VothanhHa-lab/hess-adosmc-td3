        if not (item in E.get(ref, {}) and all(item in E.get(n, {}) for n in names)):
            continue
        d_rms, d_sat, d_slew, wins, n = [], [], [], 0, 0
        for nm in names:
            for sd in E[nm][item]:
                a, b = E[nm][item][sd], E[ref][item][sd]
                d_rms.append(100 * (a["ib_rms_A"] - b["ib_rms_A"]) / b["ib_rms_A"])
                d_slew.append(100 * (a["ib_slew_rms_Aps"] - b["ib_slew_rms_Aps"]) / b["ib_slew_rms_Aps"])
                d_sat.append(100 * (a["sat_frac"] - b["sat_frac"]))
                wins += a["return"] > b["return"]
                n += 1
        kv(f"{ik}:v2vs{rk}:dibrms", fmt(np.mean(d_rms), 1))
        kv(f"{ik}:v2vs{rk}:dibrmsabs", fmt(abs(np.mean(d_rms)), 1))
        kv(f"{ik}:v2vs{rk}:dibrmsmin", fmt(np.min(d_rms), 1))
        kv(f"{ik}:v2vs{rk}:dibrmsmax", fmt(np.max(d_rms), 1))
        kv(f"{ik}:v2vs{rk}:dslew", fmt(np.mean(d_slew), 1))
        kv(f"{ik}:v2vs{rk}:dsat", fmt(np.mean(d_sat), 2))
        kv(f"{ik}:v2vs{rk}:wins", f"{wins}/{n}")

