def kv(key, val):
    lines.append(r"\expandafter\def\csname r@" + key + r"\endcsname{" + val + "}")


def mac(name, val):
    lines.append(r"\newcommand{\%s}{%s}" % (name, val))


def fmt(x, nd):
    if x is None or not np.isfinite(x):
        return "--"
    return f"{x:.{nd}f}"


E = json.load(open(os.path.join(PROC, "eval_results.json")))["results"]


def seedmean(name, item, key, scale):
    d = E[name][item]
    return float(np.mean([d[s][key] for s in d])) * scale


def nfail(name, item):
    return sum(E[name][item][s]["status"] != "ok" for s in E[name][item])


for item, ik in ITEMS.items():
    for name, ck in BASE.items():
        if item in E.get(name, {}):
            for mk, (key, sc, nd) in MET.items():
                kv(f"{ik}:{ck}:{mk}", fmt(seedmean(name, item, key, sc), nd))
            kv(f"{ik}:{ck}:fails", str(nfail(name, item)))
            kv(f"{ik}:{ck}:runs", str(len(E[name][item])))
    for gk, pat in GROUPS.items():
        names = [pat.format(s) for s in SEEDS]
        if all(item in E.get(n, {}) for n in names):
            for mk, (key, sc, nd) in MET.items():
                v = np.array([seedmean(n, item, key, sc) for n in names])
                kv(f"{ik}:{gk}:{mk}:mean", fmt(v.mean(), nd))
                kv(f"{ik}:{gk}:{mk}:std", fmt(v.std(ddof=1), nd))
                kv(f"{ik}:{gk}:{mk}:min", fmt(v.min(), nd))
                kv(f"{ik}:{gk}:{mk}:max", fmt(v.max(), nd))
            kv(f"{ik}:{gk}:fails", str(sum(nfail(n, item) for n in names)))
            kv(f"{ik}:{gk}:runs", str(sum(len(E[n][item]) for n in names)))

# paired relative change of battery RMS: proposed (v2) vs references, per item, all seed pairs
