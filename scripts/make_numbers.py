def cell(ik, ck, mk, grp):
    if grp:
        m = r"\R{%s:%s:%s:mean}" % (ik, ck, mk)
        s = r"\R{%s:%s:%s:std}" % (ik, ck, mk)
        return m + r"\,{\scriptsize$\pm$" + s + "}"
    return r"\R{%s:%s:%s}" % (ik, ck, mk)


def write_test_table(items, fname, caption, label):
    L = [r"\begin{table*}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{4pt}", r"\caption{" + caption + "}", r"\label{" + label + "}",
         r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{@{}ll" + "r" * len(COLS) + "c@{}}", r"\toprule",
         r"Cycle & Supervisor (tier 1 = A-DO-SMC) & max$|e|$ (V) & RMS $i_b$ (A) & RMS $\dot\imath_b$ (A/s) & Sat. (\%) & min $v_{sc}$ (V) & Failed runs\\",
         r"\midrule"]
    for it, lab in items:
        ik = ITEMS[it]
        first = True
        for ck, name, grp in ROWS:
            if not any(f"r@{ik}:{ck}:" in x for x in lines):
                continue
            row = [(lab if first else ""), name] + [cell(ik, ck, mk, grp) for mk, _ in COLS]
            row.append(r"\R{%s:%s:fails}/\R{%s:%s:runs}" % (ik, ck, ik, ck))
            L.append(" & ".join(row) + r"\\")
            first = False
        L.append(r"\midrule")
    L[-1] = r"\bottomrule"
    L += [r"\end{tabular}}", r"\end{table*}"]
    with open(os.path.join(OUT, fname), "w") as fh:
        fh.write("\n".join(L) + "\n")


